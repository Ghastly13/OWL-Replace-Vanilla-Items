using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading.Tasks;
using Mutagen.Bethesda;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Plugins.Records;
using Mutagen.Bethesda.Skyrim;
using Mutagen.Bethesda.Synthesis;

namespace OWLReplaceVanillaItems
{
    // Every vanilla weapon, armor or ammo that Open World Loot hands out through one of its lists, found in a mod's
    // leveled lists, containers, outfits or NPC inventories, is replaced by that list, the way OWL does it for the game's
    // own records: an Iron Sword in a mod's bandit chest becomes OWL_Weapon_Iron_Sword. Written as SkyPatcher INIs, one
    // per plugin and record type (IniFiles); the patch plugin gets no records.
    //
    // SkyPatcher replaces every instance of the item in the record, so in a record the plugin overrides (a vanilla chest
    // it adds to), an item the original record already has is left alone: replacing it would change the game's own loot
    // too. Unique NPCs, and the outfits unique NPCs wear, keep their gear (settings). Enchanted items, uniques and clothing
    // are in no OWL list and are never touched.
    public static class Program
    {
        private static Lazy<Settings> _settings = new(() => new Settings());

        public static async Task<int> Main(string[] args)
        {
            return await SynthesisPipeline.Instance
                .AddPatch<ISkyrimMod, ISkyrimModGetter>(RunPatch)
                .SetAutogeneratedSettings("Settings", "settings.json", out _settings)
                .SetTypicalOpen(GameRelease.SkyrimSE, "OWLReplaceVanillaItems.esp")
                .Run(args);
        }

        // How SkyPatcher patches each record type
        private sealed record Kind(string Signature, string Folder, string Filter, string Op, string Separator);
        private static readonly Kind LeveledListKind = new("LVLI", "leveledList", "filterByLLs", "formsToReplace", "~");
        private static readonly Kind ContainerKind = new("CONT", "container", "filterByContainers", "replaceInContainers", "~");
        private static readonly Kind OutfitKind = new("OTFT", "outfit", "filterByOutfits", "formsToReplace", "=");
        private static readonly Kind NpcKind = new("NPC_", "npc", "filterByNpcs", "objectsToReplace", "~");

        // The lines written for one plugin and record type
        private sealed class Output
        {
            public List<string> Lines { get; } = new();
            public HashSet<string> Seen { get; } = new(StringComparer.Ordinal);
        }

        public static void RunPatch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
        {
            var settings = _settings.Value;
            var report = new List<string>();
            void Log(string line)
            {
                Console.WriteLine(line);
                report.Add(line);
            }

            var inis = new IniFiles(state.DataFolderPath.Path);
            var written = new List<string>();
            try
            {
                Patch(state, settings, inis, written, Log);
            }
            finally
            {
                // Always: an INI of a plugin that is no longer patched would keep applying
                foreach (var file in inis.RemoveStale(written)) Log("Removed " + file);
                WriteReport(state, report);
            }
        }

        private static void Patch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state, Settings settings, IniFiles inis, List<string> written, Action<string> Log)
        {
            var linkCache = state.LinkCache;
            if (state.LoadOrder.TryGetValue(OwlMap.Plugin)?.Mod is not { } owlMod)
            {
                Log("Open World Loot.esp is not in the load order: nothing to patch.");
                return;
            }
            var owl = OwlMap.Build(owlMod, linkCache);
            Log("Open World Loot hands out " + owl.Targets.Count + " items through " + owl.Lists.Count + " lists.");
            if (owl.Targets.Count == 0) return;

            var plugins = PluginsToPatch(state, settings, owlMod, Log);
            var wearers = settings.Outfits && settings.SkipOutfitsOfUniqueNpcs ? new UniqueWearers(state) : null;
            if (wearers != null) Log("Unique NPCs wear " + wearers.OutfitCount + " outfits: those are not patched.");
            var existing = new ExistingPatches(state, inis.SkyPatcherFolder, inis.OtherInis);
            Log("Read " + existing.FilesRead + " SkyPatcher INIs in Open World Loot's folders (Open World Loot's and patches for other mods): "
                + existing.RecordsCleared + " records they clear and " + existing.RecordsWithItems + " they replace or remove items in are left to them"
                + (existing.LinesNotNamingRecords > 0 ? " (" + existing.LinesNotNamingRecords + " of their lines name no records by form or EditorID, and are not read)" : "") + ".");
            var refs = new SkyPatcherRefs(state, settings.UseEditorIDs);
            var outputs = new SortedDictionary<(string Folder, string Plugin), Output>();
            int replacedCount = 0, recordCount = 0, keptCount = 0, uniqueCount = 0, outfitSkipCount = 0, deferredCount = 0;

            string ItemID(FormKey item) => linkCache.TryResolve<IItemGetter>(item, out var found) && found.EditorID != null ? found.EditorID : item.ToString();

            // The item's keywords, for patches that remove items by keyword
            IEnumerable<FormKey> KeywordsOf(FormKey item)
            {
                IEnumerable<IFormLinkGetter<IKeywordGetter>>? keywords = null;
                if (linkCache.TryResolve<IWeaponGetter>(item, out var weapon)) keywords = weapon.Keywords;
                else if (linkCache.TryResolve<IArmorGetter>(item, out var armor)) keywords = armor.Keywords;
                else if (linkCache.TryResolve<IAmmunitionGetter>(item, out var ammo)) keywords = ammo.Keywords;
                return keywords?.Select(k => k.FormKey) ?? Enumerable.Empty<FormKey>();
            }

            // The INI an existing patch handles the item in the record with: clearing the record, or replacing or removing
            // the item (by form or keyword). Null when none does
            string? HandledBy(ExistingPatches.RecordPatch? patch, FormKey item)
            {
                if (patch == null) return null;
                if (patch.ClearedBy != null) return patch.ClearedBy;
                if (patch.Items.TryGetValue(item, out var file)) return file;
                foreach (var keyword in KeywordsOf(item))
                    if (patch.Keywords.TryGetValue(keyword, out file)) return file;
                return null;
            }

            // Replaces the OWL-listed items in one record of the plugin. original gives the items of the record's original
            // (the plugin that adds it), read only for a record the plugin overrides
            void Process(Kind kind, ISkyrimModGetter mod, IMajorRecordGetter record, IEnumerable<FormKey> items, Func<HashSet<FormKey>?> original, string? skipReason)
            {
                string plugin = mod.ModKey.FileName;
                string label = (record.EditorID ?? record.FormKey.ToString()) + " (" + kind.Signature + ", " + plugin + ")";
                bool overrides = record.FormKey.ModKey != mod.ModKey;
                HashSet<FormKey>? originalItems = null;
                bool originalRead = false;
                var done = new HashSet<FormKey>();
                var skipped = new List<string>();
                var patch = existing.For(record.FormKey);
                // INI -> the items left to it in this record
                var deferred = new SortedDictionary<string, List<string>>(StringComparer.OrdinalIgnoreCase);
                foreach (var item in items)
                {
                    if (item.IsNull || !owl.Targets.TryGetValue(item, out var target) || !done.Add(item)) continue;
                    string itemID = ItemID(item);
                    if (skipReason != null)
                    {
                        skipped.Add(itemID);
                        continue;
                    }
                    if (overrides)
                    {
                        if (!originalRead)
                        {
                            originalItems = original();
                            originalRead = true;
                        }
                        if (originalItems != null && originalItems.Contains(item))
                        {
                            Log("  kept in " + label + ": " + itemID + ", which the original record already has");
                            keptCount++;
                            continue;
                        }
                    }
                    if (HandledBy(patch, item) is string file)
                    {
                        if (!deferred.TryGetValue(file, out var left)) deferred[file] = left = new List<string>();
                        left.Add(itemID);
                        deferredCount++;
                        continue;
                    }
                    string line = kind.Filter + "=" + refs.Ref(record.FormKey) + ":" + kind.Op + "=" + refs.Ref(item) + kind.Separator + refs.Ref(owl.Lists[target]);
                    if (!outputs.TryGetValue((kind.Folder, plugin), out var output)) outputs[(kind.Folder, plugin)] = output = new Output();
                    if (output.Seen.Add(line))
                    {
                        output.Lines.Add("; " + (record.EditorID ?? record.FormKey.ToString()) + ": " + itemID + " -> " + target);
                        output.Lines.Add(line);
                    }
                    Log("  " + label + ": " + itemID + " -> " + target);
                    replacedCount++;
                }
                foreach (var (file, left) in deferred)
                    Log("  left to " + file + ": " + string.Join(", ", left) + " in " + label + (patch?.ClearedBy == file ? ", which it clears" : ", which it replaces or removes there"));
                if (skipped.Count > 0)
                {
                    Log("  skipped " + label + ", " + skipReason + ": " + string.Join(", ", skipped) + " left as they are");
                    if (kind == NpcKind) uniqueCount++;
                    else outfitSkipCount++;
                }
                else if (done.Count > 0) recordCount++;
            }

            ISkyrimModGetter? Defining(FormKey formKey) => state.LoadOrder.TryGetValue(formKey.ModKey)?.Mod;

            foreach (var mod in plugins)
            {
                if (settings.LeveledLists)
                    foreach (var list in mod.LeveledItems)
                        Process(LeveledListKind, mod, list, ItemsOf(list),
                            () => Defining(list.FormKey)?.LeveledItems.TryGetValue(list.FormKey, out var o) == true ? ItemsOf(o!).ToHashSet() : null, null);
                if (settings.Containers)
                    foreach (var container in mod.Containers)
                        Process(ContainerKind, mod, container, ItemsOf(container),
                            () => Defining(container.FormKey)?.Containers.TryGetValue(container.FormKey, out var o) == true ? ItemsOf(o!).ToHashSet() : null, null);
                if (settings.Outfits)
                    foreach (var outfit in mod.Outfits)
                        Process(OutfitKind, mod, outfit, ItemsOf(outfit),
                            () => Defining(outfit.FormKey)?.Outfits.TryGetValue(outfit.FormKey, out var o) == true ? ItemsOf(o!).ToHashSet() : null,
                            wearers?.Describe(outfit.FormKey));
                if (settings.Npcs)
                    foreach (var npc in mod.Npcs)
                    {
                        string? unique = settings.SkipUniqueNpcs && linkCache.TryResolve<INpcGetter>(npc.FormKey, out var winner) && UniqueWearers.IsUnique(winner) ? "a unique NPC" : null;
                        Process(NpcKind, mod, npc, ItemsOf(npc),
                            () => Defining(npc.FormKey)?.Npcs.TryGetValue(npc.FormKey, out var o) == true ? ItemsOf(o!).ToHashSet() : null, unique);
                    }
            }

            foreach (var ((folder, plugin), output) in outputs)
            {
                if (output.Lines.Count == 0) continue;
                string path = inis.Write(folder, plugin, output.Lines, out bool changed);
                written.Add(path);
                int count = output.Lines.Count / 2;
                Log((changed ? "Wrote " : "Unchanged ") + path + " (" + count + (count == 1 ? " replacement)" : " replacements)"));
            }

            // INIs the xEdit script wrote for the plugins patched here: their lines still apply alongside these
            var patched = new HashSet<string>(outputs.Keys.Select(k => k.Plugin), StringComparer.OrdinalIgnoreCase);
            foreach (var (plugin, files) in inis.XEditReplacements)
                if (patched.Contains(plugin))
                    foreach (var file in files)
                        Log("NOTE: " + file + " was written by the xEdit script OWL_Replace_Vanilla_Items.pas for " + plugin + ". This patcher's INIs replace it: remove it, or its lines (any for unique NPCs included) keep applying.");

            Log(replacedCount + " vanilla items replaced by OWL lists in " + recordCount + " records of " + patched.Count + " plugins, "
                + keptCount + " kept because the original record has them, " + deferredCount + " left to the patches in Open World Loot's folders, "
                + uniqueCount + " unique NPCs and " + outfitSkipCount + " outfits unique NPCs wear skipped (all listed above).");
        }

        // The plugins whose records are patched, in load order. Plugins Open World Loot already has patches for are patched
        // too, around what those patches do (ExistingPatches)
        private static List<ISkyrimModGetter> PluginsToPatch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state, Settings settings, ISkyrimModGetter owlMod, Action<string> Log)
        {
            var only = new HashSet<ModKey>(settings.OnlyPlugins);
            var skipped = new HashSet<ModKey>(settings.SkippedPlugins);
            var owlMasters = new HashSet<ModKey>(owlMod.ModHeader.MasterReferences.Select(m => m.Master));
            var plugins = new List<ISkyrimModGetter>();
            foreach (var listing in state.LoadOrder.ListedOrder)
            {
                if (listing.Mod is not { } mod) continue;
                var key = listing.ModKey;
                if (skipped.Contains(key)) continue;
                if (IsOwlPlugin(key))
                {
                    if (key != OwlMap.Plugin) Log("Left out " + key.FileName + ": an Open World Loot plugin");
                    continue;
                }
                if (only.Count > 0)
                {
                    if (only.Contains(key)) plugins.Add(mod);
                    continue;
                }
                if (owlMasters.Contains(key)) continue;
                plugins.Add(mod);
            }
            foreach (var key in only.Where(k => state.LoadOrder.TryGetValue(k) == null))
                Log("NOTE: " + key.FileName + " (in \"Only these plugins\") is not in the load order.");
            return plugins;
        }

        // Open World Loot's own plugins, by name: Open World Loot.esp and its patches (Open World Loot - Heavy Armory
        // Patch.esp, ...). Never patched, even when listed in "Only these plugins"
        private static bool IsOwlPlugin(ModKey key) => key.FileName.ToString().Contains("Open World Loot", StringComparison.OrdinalIgnoreCase);

        private static IEnumerable<FormKey> ItemsOf(ILeveledItemGetter list) =>
            list.Entries?.Select(e => e.Data?.Reference.FormKey ?? FormKey.Null) ?? Enumerable.Empty<FormKey>();

        private static IEnumerable<FormKey> ItemsOf(IContainerGetter container) =>
            container.Items?.Select(e => e.Item.Item.FormKey) ?? Enumerable.Empty<FormKey>();

        private static IEnumerable<FormKey> ItemsOf(IOutfitGetter outfit) =>
            outfit.Items?.Select(l => l.FormKey) ?? Enumerable.Empty<FormKey>();

        private static IEnumerable<FormKey> ItemsOf(INpcGetter npc) =>
            npc.Items?.Select(e => e.Item.Item.FormKey) ?? Enumerable.Empty<FormKey>();

        // Everything logged, also written to "OWL replacements.txt" in the patcher's data folder
        private static void WriteReport(IPatcherState<ISkyrimMod, ISkyrimModGetter> state, List<string> report)
        {
            string? folder = state.ExtraSettingsDataPath?.Path;
            if (string.IsNullOrEmpty(folder)) return;
            Directory.CreateDirectory(folder);
            File.WriteAllLines(Path.Combine(folder, "OWL replacements.txt"), report);
        }
    }
}
